CREATE TABLE IF NOT EXISTS public.spro_l1_l6_sequence (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_code          VARCHAR(10),
    module_name          TEXT NOT NULL,
    language             TEXT NOT NULL DEFAULT 'E',
    tree_id              TEXT NOT NULL,
    node_id              TEXT NOT NULL,
    parent_node_id       TEXT,
    brother_id           TEXT,
    level_no             INTEGER NOT NULL CHECK (level_no BETWEEN 1 AND 6),
    sequence_no          INTEGER NOT NULL CHECK (sequence_no > 0),
    node_name            TEXT NOT NULL,
    node_text            TEXT,
    tree_text            TEXT,
    node_type            TEXT,
    activity             TEXT,
    reference_type       TEXT,
    reference_object     TEXT,
    customizing_object   TEXT,
    table_name           TEXT,
    source_system        TEXT NOT NULL DEFAULT 'ODATA',
    hierarchy_complete   BOOLEAN NOT NULL DEFAULT FALSE,
    is_active            BOOLEAN NOT NULL DEFAULT TRUE,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT uq_spro_l1_l6_node
        UNIQUE (module_name, language, tree_id, node_id),
    CONSTRAINT uq_spro_l1_l6_module_code_node
        UNIQUE (module_code, language, tree_id, node_id)
);

CREATE INDEX IF NOT EXISTS ix_spro_l1_l6_lookup
    ON public.spro_l1_l6_sequence
       (module_code, module_name, language, is_active);

CREATE INDEX IF NOT EXISTS ix_spro_l1_l6_parent_sequence
    ON public.spro_l1_l6_sequence
       (module_code, module_name, language, tree_id, parent_node_id, sequence_no);

CREATE INDEX IF NOT EXISTS ix_spro_l1_l6_level_sequence
    ON public.spro_l1_l6_sequence
       (module_code, module_name, language, level_no, sequence_no);

ALTER TABLE public.spro_l1_l6_sequence ENABLE ROW LEVEL SECURITY;

-- Backend access is through the Supabase service-role key.
-- No client-side policy is required for this cache table.

CREATE OR REPLACE FUNCTION public.touch_spro_l1_l6_sequence_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_spro_l1_l6_sequence_updated_at
    ON public.spro_l1_l6_sequence;

CREATE TRIGGER trg_spro_l1_l6_sequence_updated_at
BEFORE UPDATE ON public.spro_l1_l6_sequence
FOR EACH ROW
EXECUTE FUNCTION public.touch_spro_l1_l6_sequence_updated_at();
